"""Regenerate the natural-English demo corpus (data/natural/).

Internal tool for producing the shipped persona corpus. The corpus itself
is described in user-facing docs simply as natural-English prose by five
author personas — this script is how it was produced.

Design goals (see README "The demo corpora"):

  * Natural English with a large open vocabulary and realistic word
    statistics. LERF (Ch.6) is defined over natural language, and its
    advantage over count-based estimators appears exactly when the
    sample misses rare types of a rich vocabulary whose overall shape
    follows ordinary English. Prose is therefore generated by a local
    GPT-2 continuing a large pool of everyday-topic seed paragraphs.
  * Authorship signal carried by STYLE, not topic — mirroring the
    thesis's real benchmarks (e.g. CCAT50), where authors write about
    the same subjects and differ in function-word habits. All personas
    draw seeds from the same shared topic pool; each persona applies a
    distinct stylistic fingerprint (preferred adverbs and connectives,
    sentence-length rhythm, mild punctuation habits) in a post-
    processing pass over the generated prose.
  * Size: 50 train / 20 test documents per author, ~120-350 words each,
    so the thesis's headline Linear SVM can learn from LERF profiles.

Usage:
    python scripts/generate_natural_corpus.py            # write to data/natural/
    python scripts/generate_natural_corpus.py --n-train 50 --n-test 20
"""

