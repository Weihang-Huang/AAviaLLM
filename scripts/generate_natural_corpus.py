def _generate_continuation(prompt: str, gen, tokenizer, device,
                           max_new_tokens: int = 250) -> str:
    """Continue a persona prompt with a local GPT-2, using PURE sampling
    (temperature 1.0, no top-k/top-p truncation, no repetition penalty).

    Unconstrained sampling is essential to the Ch.6 demo result: LERF
    estimates what GPT-2 *expects*, so the corpus must be drawn from
    GPT-2's own generative distribution. Any truncation (top-k/top-p)
    or repetition penalty distorts exactly the high-frequency types
    ('.', ',', ' the') that dominate LMSE, and measurably flips the
    LERF-vs-MLE comparison.
    """
    import torch

    enc = tokenizer(prompt, return_tensors="pt").to(device)
    with torch.no_grad():
        out = gen.generate(
            input_ids=enc["input_ids"],
            attention_mask=enc["attention_mask"],
            max_new_tokens=max_new_tokens,
            do_sample=True,
            temperature=1.0,
            top_k=0,
            top_p=1.0,
            pad_token_id=tokenizer.eos_token_id,
        )
    text = tokenizer.decode(out[0], skip_special_tokens=True)
    # Return the continuation past the prompt.
    return text[len(prompt):].strip()


def _make_doc(persona: dict, rng: random.Random, gen, tokenizer, device,
              prompt: str) -> str:
    """One document = 1 persona prompt sentence + a single pure-sampled
    GPT-2 continuation (~200 tokens), with the persona style pass applied
    to the continuation only.

    The prompt (human-written persona-domain prose) anchors the topic;
    the continuation supplies the bulk of the text and the open
    vocabulary (hallucinated names, rare words) that the Ch.6 LERF
    result needs; the style pass adds the mid-frequency persona
    markers that the Ch.7 attribution needs.
    """
    cont = _generate_continuation(prompt, gen, tokenizer, device)
    # A pure-sampled continuation occasionally emits an early EOS; retry
    # (fresh sampling noise) until the document has real prose bulk.
    retries = 0
    while len(cont.split()) < 40 and retries < 4:
        cont = _generate_continuation(prompt, gen, tokenizer, device)
        retries += 1
    sents = _split_sentences(cont)
    styled = _apply_style(sents, persona, rng)
    if styled:
        # Group sentences into short paragraphs separated by single
        # newlines: GPT-2's expected newline frequency (~2% of tokens)
        # matches WebText-style layout of short paragraphs; a single
        # unbroken block (or fewer, double-newline paragraphs)
        # under-represents '\n' and visibly distorts LERF's estimate
        # of that high-mass type.
        per_para = max(2, len(styled) // 5)
        paras = [" ".join(styled[i:i + per_para])
                 for i in range(0, len(styled), per_para)]
        body = prompt + "\n" + "\n".join(paras)
    else:
        body = prompt
    return f"<BOS>{body}<EOS>"


def generate(out_dir: str, n_train: int, n_test: int, seed: int = SEED,
             model_name: str = "gpt2") -> tuple[pd.DataFrame, pd.DataFrame]:
    import torch
    from transformers import AutoTokenizer, AutoModelForCausalLM

    if torch.cuda.is_available():
        device = "cuda"
    elif hasattr(torch, "xpu") and torch.xpu.is_available():
        device = "xpu"
    else:
        device = "cpu"
    tokenizer = AutoTokenizer.from_pretrained(model_name)
    gen = AutoModelForCausalLM.from_pretrained(model_name).to(device)
    gen.eval()
    torch.manual_seed(seed)

    rng = random.Random(seed)
    rows: list[dict] = []
    n_per_author = n_train + n_test
    for persona in PERSONAS:
        tag = persona["tag"]
        prompts = PERSONA_SEEDS[tag]
        for i in range(n_per_author):
            prompt = prompts[i % len(prompts)]
            rows.append({TEXT_COL: _make_doc(persona, rng, gen,
                                              tokenizer, device, prompt),
                         TAG_COL: tag})

    df = pd.DataFrame(rows)
    # Stratified split: first n_train shuffled docs per author -> train.
    train_parts, test_parts = [], []
    for persona in PERSONAS:
        tag = persona["tag"]
        g = df[df[TAG_COL] == tag].sample(frac=1.0, random_state=seed)
        train_parts.append(g.iloc[:n_train])
        test_parts.append(g.iloc[n_train:])
    train_df = pd.concat(train_parts).reset_index(drop=True)
    test_df = pd.concat(test_parts).reset_index(drop=True)

    os.makedirs(out_dir, exist_ok=True)
    train_df.to_csv(os.path.join(out_dir, "train.csv"),
                    index=False, encoding="utf-8")
    test_df.to_csv(os.path.join(out_dir, "test.csv"),
                   index=False, encoding="utf-8")
    return train_df, test_df


