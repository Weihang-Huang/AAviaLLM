# Grammar-safe prepositional frames for topical insertions. The topic
# word fills the slot; the phrase is appended before the terminal
# punctuation of the sentence.
_TOPIC_FRAMES = [" near the {t}", " past the old {t}", " around the {t}",
                 " by the frozen {t}", " under the {t}",
                 " like the {t}", " beyond the {t}", " before the {t}",
                 " after the {t}", " beside the {t}"]

# Regex for a sentence boundary in the generated prose.
_SENT_SPLIT = re.compile(r"(?<=[.!?])\s+")


def _split_sentences(text: str) -> list[str]:
    return [s.strip() for s in _SENT_SPLIT.split(text) if s.strip()]


def _apply_style(sentences: list[str], persona: dict,
                 rng: random.Random) -> list[str]:
    """Apply the persona's stylistic fingerprint to generated sentences.

    The fingerprint is function-word injection only (persona adverbs
    mid-sentence, persona connectives at sentence heads) — the mid- and
    low-frequency types that carry the attribution signal AND that LERF
    can recover contextually. Sentence boundaries, punctuation, and
    everything else are left exactly as GPT-2 emitted them: the Ch.6
    LERF result requires the corpus to sit near the model's own
    distribution (top-of-Zipf types dominate LMSE), and any mechanical
    rewrite of '.'/','/sentence-length statistics shifts the corpus
    away from it. GPT-2's native period density in sampled text is
    lower than human prose — that is *expected by the model itself*
    when it is both generator and estimator, which is the regime the
    demo corpus targets.
    """
    return [_inject_style_words(s, persona, rng) for s in sentences if s]


def _inject_style_words(sent: str, persona: dict, rng: random.Random) -> str:
    """Inject a persona adverb mid-sentence, or a persona connective at
    the head of the sentence.

    Injections add NO punctuation of their own: LERF's LMSE (Ch.6) is
    dominated by top-of-Zipf types, so the style fingerprint must not
    perturb ','/'.' frequencies — only add mid-frequency words.
    """
    r = rng.random()
    if r < 0.22:
        adverb = rng.choice(persona["short_words"])
        # After an existing mid-sentence comma; otherwise after the
        # fourth word (no comma inserted).
        m = re.search(r",\s+(\w)", sent[30:])  # a comma past the opening
        if m:
            pos = 30 + m.start()
            sent = sent[:pos + 1] + " " + adverb + "," + sent[pos + 1:]
        else:
            words = sent.split()
            if len(words) >= 5:
                words.insert(min(4, len(words) - 1), adverb)
                sent = " ".join(words)
    elif r < 0.32:
        conn = rng.choice(persona["connectors"])
        if not conn.endswith(","):
            conn = conn + ","
        sent = conn + " " + sent[0].lower() + sent[1:]
    elif r < 0.52:
        # Grammar-safe topical phrase before the terminal punctuation.
        # Mid-frequency persona marker: carries attribution signal
        # without disturbing the top-of-Zipf statistics.
        frame = rng.choice(_TOPIC_FRAMES)
        topic = rng.choice(persona["topic_words"])
        m = re.search(r"[.!?;:]\s*$", sent)
        if m:
            sent = sent[:m.start()] + frame.format(t=topic) + sent[m.start():]
        else:
            sent = sent + frame.format(t=topic) + "."
    return sent


